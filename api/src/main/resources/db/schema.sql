-- Payment Approval and Reconciliation Platform: baseline JDBC schema (supplied baseline).
-- Synthetic data only. Works on H2 in PostgreSQL mode (the default local store) and on
-- PostgreSQL 15 or later. Never put a password in this file.
--
-- The schema enforces the business invariants itself: USD only, amounts 1..999999999 cents,
-- known statuses, one request per (supplier, invoice), one settlement per request, and
-- attributable, gap-free history keyed by (request_id, seq).

CREATE TABLE IF NOT EXISTS payment_requests (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id    VARCHAR(8)   NOT NULL CHECK (regexp_like(supplier_id, '^SUP-[0-9]{4}$')),
    invoice_number VARCHAR(64)  NOT NULL CHECK (char_length(trim(invoice_number)) > 0),
    amount_cents   BIGINT       NOT NULL CHECK (amount_cents BETWEEN 1 AND 999999999),
    currency       CHAR(3)      NOT NULL CHECK (currency = 'USD'),
    requested_by   VARCHAR(32)  NOT NULL,
    status         VARCHAR(16)  NOT NULL
        CHECK (status IN ('SUBMITTED', 'APPROVED', 'REJECTED', 'CANCELLED', 'PAID')),
    CONSTRAINT uq_payment_requests_invoice UNIQUE (supplier_id, invoice_number)
);

CREATE SEQUENCE IF NOT EXISTS payment_request_ids START WITH 1;

CREATE TABLE IF NOT EXISTS payment_events (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER      NOT NULL REFERENCES payment_requests (id),
    seq        INTEGER      NOT NULL CHECK (seq >= 1),
    actor_id   VARCHAR(32)  NOT NULL,
    action     VARCHAR(32)  NOT NULL,
    detail     VARCHAR(512) NOT NULL,
    CONSTRAINT uq_payment_events_seq UNIQUE (request_id, seq)
);

CREATE TABLE IF NOT EXISTS settlements (
    reference    VARCHAR(32) PRIMARY KEY,
    request_id   INTEGER     NOT NULL UNIQUE REFERENCES payment_requests (id),
    amount_cents BIGINT      NOT NULL CHECK (amount_cents BETWEEN 1 AND 999999999),
    currency     CHAR(3)     NOT NULL CHECK (currency = 'USD')
);
